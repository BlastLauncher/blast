function shortcut(
  key: KeyEquivalent,
  macOS: KeyModifier[],
  Windows: KeyModifier[],
  windowsKey: KeyEquivalent = key,
) {
  return { macOS: { modifiers: macOS, key }, Windows: { modifiers: Windows, key: windowsKey } };
}

