import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import type { Inventory } from "./inventory.ts";
import { INVENTORY_PATH } from "./generate-inventory.ts";

export const STUBS_PATH = "packages/runtime/src/api/unsupported.generated.ts";
export const VALUE_KINDS = new Set([
  "namespace",
  "component",
  "function",
  "const",
  "class",
  "enum",
]);

export function generateStubs(root: string): string {
  const inventory = JSON.parse(readFileSync(join(root, INVENTORY_PATH), "utf8")) as Inventory;
  const indexPath = join(root, "packages/runtime/src/api/index.ts");
  const aliases = new Set(
    existsSync(indexPath)
      ? [
          ...readFileSync(indexPath, "utf8").matchAll(/export const (\w+) = [A-Z]\w*(?:\.\w+)*;/g),
        ].map((match) => match[1])
      : [],
  );
  const names = inventory.entries
    .filter(
      (entry) =>
        !entry.path.includes(".") && VALUE_KINDS.has(entry.kind) && !aliases.has(entry.path),
    )
    .map((entry) => entry.path)
    .toSorted();
  return [
    "// Generated by scripts/compat/generate-stubs.ts; do not edit.",
    'import * as implemented from "./implemented.ts";',
    'import { createApi } from "./unsupported.ts";',
    "const api = createApi(implemented);",
    ...names.map((name) => `export const ${name} = api(${JSON.stringify(name)});`),
    "",
  ].join("\n");
}

export function checkStubs(root: string): string[] {
  const path = join(root, STUBS_PATH);
  return existsSync(path) && readFileSync(path, "utf8") === generateStubs(root)
    ? []
    : [`${STUBS_PATH}: missing or stale; run \`bun run compat:stubs\``];
}

if (import.meta.main) {
  writeFileSync(join(process.cwd(), STUBS_PATH), generateStubs(process.cwd()));
}
